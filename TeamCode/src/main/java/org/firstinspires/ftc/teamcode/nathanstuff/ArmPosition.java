package org.firstinspires.ftc.teamcode.nathanstuff;

public class ArmPosition {
    double wristPitch;
    double wristRoll;
    int wormGear;
    int slides;

    public ArmPosition(double wristPitch, double wristRoll, int wormGear, int slides) {
        this.wristPitch = wristPitch;
        this.wristRoll = wristRoll;
        this.wormGear = wormGear;
        this.slides = slides;
    }
}
